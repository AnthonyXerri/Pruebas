-- Comprobación (no guardar): cuántas solicitantes de Natalidad tienen fecha de nacimiento informada, por año de convocatoria.
SELECT
    CAST(E."NMEJERCICIOCONV" AS VARCHAR)
    || ' | con fecha ' || CAST(SUM(CASE WHEN I."FC_NACIMIENTO" IS NOT NULL THEN 1 ELSE 0 END) AS VARCHAR)
    || ' | sin fecha ' || CAST(SUM(CASE WHEN I."FC_NACIMIENTO" IS NULL THEN 1 ELSE 0 END) AS VARCHAR) AS "ID"
FROM "GSTA_V_INTERESADOS" I
INNER JOIN (
    SELECT DISTINCT "CDEXPEDIENTE", "NMEJERCICIOCONV"
    FROM "GSTA_V_CEL_EXPEDIENTE"
    WHERE "CDAPLICACION" = 'D032' AND "CDPROCEDIMIENTO" = '3163'
) E ON I."CD_EXPEDIENTE" = E."CDEXPEDIENTE"
WHERE I."TIPO" = 'Interesado' AND I."IT_PRINCIPAL" = 'S'
GROUP BY E."NMEJERCICIOCONV"
ORDER BY E."NMEJERCICIOCONV"
