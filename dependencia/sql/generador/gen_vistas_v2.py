def vista(tabla):
    return 'SIDM_V_DEP_' + (tabla[5:] if tabla.startswith('SIDM_') else tabla)

def bloque(tabla, uso, cols, fuera):
    dentro = [c for c in cols if c not in fuera]
    v = vista(tabla)
    L = [f'--{tabla}', f'-- Uso: {uso}', f'-- Columnas: {len(dentro)} de {len(cols)}.']
    if fuera:
        grupos = {}
        for c in cols:
            if c in fuera:
                grupos.setdefault(fuera[c], []).append(c)
        partes = [f"{MOTIVO[m]}: {', '.join(cs)}" for m, cs in grupos.items()]
        L.append('-- Fuera:')
        for p in partes:
            # partir líneas largas
            linea = '--   ' + p
            while len(linea) > 110:
                corte = linea.rfind(', ', 0, 110)
                L.append(linea[:corte + 1])
                linea = '--     ' + linea[corte + 2:]
            L.append(linea)
    if tabla.startswith('SUCA_'):
        L.append('-- Nota DBA: tabla del esquema SUCA; el propietario de la vista necesita SELECT WITH GRANT OPTION sobre ella.')
    L.append(f'DROP VIEW {v};')
    L.append(f'CREATE VIEW {v} AS ')
