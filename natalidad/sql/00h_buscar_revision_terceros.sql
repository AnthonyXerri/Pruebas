-- Comprobación (no guardar): buscar en la bitácora la revisión de conformidad, la propuesta a nómina y los pasos de terceros.
-- Excluye líneas que suelen llevar DNI (ICDA, notificaciones, acuses, documentos aportados) y las de documentos requeridos.
SELECT
    LEFT(A."DSACTIVIDAD", 90)
    || ' | ' || CAST(COUNT(*) AS VARCHAR) || ' veces'
    || ' | ' || CAST(COUNT(DISTINCT A."CDEXPEDIENTE") AS VARCHAR) || ' exp' AS "ID"
FROM "GSTA_V_CEL_ACTIVIDAD" A
WHERE A."CDEXPEDIENTE" IN (
    SELECT "CDEXPEDIENTE"
    FROM "GSTA_V_CEL_EXPEDIENTE"
    WHERE "CDAPLICACION" = 'D032' AND "CDPROCEDIMIENTO" = '3163'
)
  AND (   UPPER(A."DSACTIVIDAD") LIKE '%CONFORM%'
       OR UPPER(A."DSACTIVIDAD") LIKE '%REVISAD%'
       OR UPPER(A."DSACTIVIDAD") LIKE '%REVISI%N%'
       OR UPPER(A."DSACTIVIDAD") LIKE '%INSTRUCCI%'
       OR UPPER(A."DSACTIVIDAD") LIKE '%PROPUESTA%'
       OR UPPER(A."DSACTIVIDAD") LIKE '%N_MINA%'
       OR UPPER(A."DSACTIVIDAD") LIKE '%TERCERO%'
       OR UPPER(A."DSACTIVIDAD") LIKE '%NEXUS%'
       OR UPPER(A."DSACTIVIDAD") LIKE '%FICHERO%'
       OR UPPER(A."DSACTIVIDAD") LIKE '%REMESA%')
  AND UPPER(A."DSACTIVIDAD") NOT LIKE '%ICDA%'
  AND UPPER(A."DSACTIVIDAD") NOT LIKE '%NOTIFICACI%'
  AND UPPER(A."DSACTIVIDAD") NOT LIKE '%ACUSE%'
  AND UPPER(A."DSACTIVIDAD") NOT LIKE '%DOCUMENTO REQUERIDO%'
  AND UPPER(A."DSACTIVIDAD") NOT LIKE 'DOCUMENTO APORTADO%'
GROUP BY LEFT(A."DSACTIVIDAD", 90)
ORDER BY COUNT(*) DESC
LIMIT 60
